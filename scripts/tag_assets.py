#!/usr/bin/env python3
"""Scan asset folders and build assets/catalog.json with measured tags and license fields.

Usage:
  python scripts/tag_assets.py [--roots assets/local assets/library assets/cache] [--vocals]
                               [--only-new] [--out assets/catalog.json]
  python scripts/tag_assets.py find "short bright whoosh" [--kind sfx] [--limit 5]
  python scripts/tag_assets.py kit        fill assets/kit/manifest.json role slots from tagged packs

Audio: duration, integrated loudness, spectral brightness (centroid), attack time, BPM, key,
energy curve, a role guess (whoosh, hit, riser, pop, click, ambience, music...), and with
--vocals whether a track has sung or spoken words (Whisper tiny), so vocal music is never
run under speech.
Video and images: resolution, duration, dominant colours, motion amount.

Licenses: each pack folder may hold a LICENSE.json ({"source", "license", "commercial",
"attribution", "restrictions", "license_checked"}); known packs (Sonniss, Kenney, Mixkit) are
recognised by folder name; anything else is marked commercial: null (unknown) and is not used
in commercial projects until the user confirms.

Embeddings: an audio-text model (CLAP) needs torch, which this environment does not have;
`find` ranks by tags, role and measured features instead and says so. Computing embeddings
would be inference on licensed files, which pack terms checked so far allow; ML training is
not (Sonniss forbids it).
"""
from __future__ import annotations

import argparse
import datetime as _dt
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np  # noqa: E402

from lib.common import AUDIO_EXT, IMAGE_EXT, VIDEO_EXT, fail, file_hash, log, read_json, run, write_json  # noqa: E402

SKILL = Path(__file__).resolve().parent.parent
KNOWN_PACKS = {
    "sonniss": {"source": "Sonniss GDC bundle", "license": "Sonniss royalty-free", "commercial": True, "attribution": None,
                "restrictions": ["no resale as sound effects", "no ML training"], "license_checked": "2026-11-15"},
    "kenney": {"source": "Kenney", "license": "CC0", "commercial": True, "attribution": None, "restrictions": [],
               "license_checked": "2026-11-15"},
    "pve_synth": {"source": "pro-video-editor synthesized kit", "license": "generated by the skill; no third-party rights",
                  "commercial": True, "attribution": None, "restrictions": [], "license_checked": "n/a (own work)"},
    "mixkit": {"source": "Mixkit", "license": "Mixkit free license (verify per item)", "commercial": None, "attribution": None,
               "restrictions": ["license text not verified at build time"], "license_checked": None},
}
ROLE_WORDS = {"whoosh": "transition_whoosh", "swish": "transition_whoosh", "swoosh": "transition_whoosh",
              "riser": "riser", "rise": "riser", "hit": "impact_hit", "impact": "impact_hit", "boom": "impact_hit",
              "pop": "text_pop", "click": "click", "ding": "ding", "bell": "ding", "glitch": "glitch",
              "shutter": "shutter", "camera": "shutter", "notification": "notification", "swipe": "swipe",
              "paper": "paper", "drop": "sub_drop", "sub": "sub_drop", "ambience": "ambience", "ambient": "ambience",
              "room": "room_tone", "tone": "room_tone"}
KEYS = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
MAJOR = np.array([6.35, 2.23, 3.48, 2.33, 4.38, 4.09, 2.52, 5.19, 2.39, 3.66, 2.29, 2.88])   # Krumhansl-Kessler
MINOR = np.array([6.33, 2.68, 3.52, 5.38, 2.60, 3.53, 2.54, 4.75, 3.98, 2.69, 3.34, 3.17])


def pack_license(path: Path) -> dict:
    for parent in path.parents:
        lic = parent / "LICENSE.json"
        if lic.exists():
            return read_json(lic)
        for k, v in KNOWN_PACKS.items():
            if k in parent.name.lower():
                return dict(v)
        if parent.name in ("local", "library", "cache"):
            break
    return {"source": path.parent.name, "license": "unknown", "commercial": None, "attribution": None,
            "restrictions": ["license unknown: confirm before commercial use"], "license_checked": None}


def audio_tags(path: Path, vocals: bool) -> dict:
    import librosa
    import soundfile as sf
    tmp = SKILL / "assets" / "cache" / "tag_tmp.wav"
    run(["ffmpeg", "-v", "error", "-y", "-i", str(path), "-ac", "1", "-ar", "22050", str(tmp)])
    x, sr = sf.read(str(tmp), dtype="float32")
    dur = x.size / sr
    st = np.stack([x, x], 1)
    import pyloudnorm as pyln
    lufs = float(pyln.Meter(sr).integrated_loudness(st)) if dur > 0.5 else None
    cent = float(np.median(librosa.feature.spectral_centroid(y=x, sr=sr)))
    env = np.abs(x)
    attack = float(np.argmax(env > 0.9 * env.max()) / sr) if env.max() > 0 else None
    out = {"duration_s": round(dur, 3), "lufs": None if lufs is None or not np.isfinite(lufs) else round(lufs, 1),
           "brightness_hz": round(cent), "attack_s": None if attack is None else round(attack, 3)}
    if dur >= 8:
        tempo, _ = librosa.beat.beat_track(y=x, sr=sr)
        chroma = librosa.feature.chroma_cqt(y=x, sr=sr).mean(1)
        scores = [(np.corrcoef(np.roll(MAJOR, k), chroma)[0, 1], f"{KEYS[k]} major") for k in range(12)] + \
                 [(np.corrcoef(np.roll(MINOR, k), chroma)[0, 1], f"{KEYS[k]} minor") for k in range(12)]
        rms = librosa.feature.rms(y=x)[0]
        step = max(1, rms.size // 40)
        energy = [round(float(rms[i:i + step].mean() / (rms.max() + 1e-9)), 2) for i in range(0, rms.size, step)]
        out.update(bpm=round(float(np.atleast_1d(tempo)[0]), 1), key=max(scores)[1], energy=energy)
        if vocals:
            out["vocals"] = has_vocals(path)
    tmp.unlink(missing_ok=True)
    return out


_whisper = None


def has_vocals(path: Path) -> dict:
    """Run Whisper tiny on the track: confident words mean vocals (sung or spoken)."""
    global _whisper
    import soundfile as sf
    tmp = SKILL / "assets" / "cache" / "voc_tmp.wav"
    run(["ffmpeg", "-v", "error", "-y", "-i", str(path), "-ac", "1", "-ar", "16000", str(tmp)])
    x, _ = sf.read(str(tmp), dtype="float32")
    tmp.unlink(missing_ok=True)
    if _whisper is None:
        from faster_whisper import WhisperModel
        _whisper = WhisperModel("tiny", device="cpu", compute_type="int8")
    segs, _ = _whisper.transcribe(x, vad_filter=True, word_timestamps=True)
    words = [w for s in segs for w in (s.words or []) if w.probability >= 0.6]
    return {"present": len(words) >= 8, "confident_words": len(words),
            "sample": " ".join(w.word.strip() for w in words[:12]), "method": "whisper tiny, words with p >= 0.6"}


def role_guess(path: Path, t: dict) -> str:
    name = path.stem.lower()
    for w, r in ROLE_WORDS.items():
        if w in name:
            return r
    d = t.get("duration_s", 0)
    if d >= 30:
        return "music" if t.get("bpm") else "ambience"
    if d < 0.15:
        return "click"
    if d < 0.6:
        return "text_pop" if (t.get("attack_s") or 1) < 0.02 else "transition_whoosh"
    if (t.get("attack_s") or 0) > 0.6 * d:
        return "riser"
    return "impact_hit"


def visual_tags(path: Path, kind: str) -> dict:
    import cv2
    if kind == "image":
        img = cv2.imread(str(path))
        if img is None:
            return {"error": "unreadable image"}
        frames, dur = [img], None
    else:
        cap = cv2.VideoCapture(str(path))
        n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT)); fps = cap.get(cv2.CAP_PROP_FPS) or 30
        frames = []
        for f in np.linspace(0, max(0, n - 1), 5).astype(int):
            cap.set(cv2.CAP_PROP_POS_FRAMES, int(f)); ok, fr = cap.read()
            if ok:
                frames.append(fr)
        cap.release()
        dur = n / fps if fps else None
    if not frames:
        return {"error": "no frames"}
    h, w = frames[0].shape[:2]
    small = cv2.resize(frames[len(frames) // 2], (64, 64)).reshape(-1, 3).astype(np.float32)
    _, lab, cen = cv2.kmeans(small, 4, None, (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 20, 1.0), 3,
                             cv2.KMEANS_PP_CENTERS)
    order = np.argsort(-np.bincount(lab.ravel(), minlength=4))
    colors = ["#%02x%02x%02x" % tuple(int(c) for c in cen[i][::-1]) for i in order]
    motion = None
    if len(frames) > 1:
        g = [cv2.cvtColor(cv2.resize(f, (160, 90)), cv2.COLOR_BGR2GRAY).astype(float) for f in frames]
        motion = round(float(np.mean([np.abs(a - b).mean() for a, b in zip(g, g[1:])])), 2)
    return {"width": w, "height": h, "duration_s": None if dur is None else round(dur, 2), "colors": colors, "motion": motion}


def tier_of(path: Path) -> int:
    p = path.as_posix()
    return 1 if "/assets/local/" in p else 2 if "/assets/kit/" in p else 3 if "/assets/library/" in p else 4


def build(roots: list[Path], vocals: bool, only_new: bool, out: Path) -> dict:
    cat = read_json(out) if out.exists() else {"version": 1, "assets": []}
    by_path = {e["path"]: e for e in cat["assets"]}
    n_new = 0
    for root in roots:
        if not root.exists():
            continue
        for p in sorted(root.rglob("*")):
            ext = p.suffix.lower()
            if not p.is_file() or ext not in AUDIO_EXT | VIDEO_EXT | IMAGE_EXT or p.name.startswith(("tag_tmp", "voc_tmp")):
                continue
            p = p.resolve()
            relp = p.relative_to(SKILL).as_posix() if SKILL in p.parents else p.as_posix()
            old = by_path.get(relp)
            if only_new and old and old.get("hash") == file_hash(p):
                continue
            kind = "audio" if ext in AUDIO_EXT else "video" if ext in VIDEO_EXT else "image"
            log(f"tag {relp}")
            try:
                t = audio_tags(p, vocals) if kind == "audio" else visual_tags(p, kind)
            except Exception as e:
                log(f"  skipped: {e}"); continue
            lic = pack_license(p)
            if old and old.get("license") not in (None, "unknown"):
                lic = {k: old.get(k) for k in ("source", "license", "commercial", "attribution", "restrictions",
                                               "license_checked", "url", "title", "creator")}
            if kind == "audio":
                role = role_guess(p, t)
                kind = "music" if role == "music" else "sfx"
            else:
                role = "broll"
            aid = (old or {}).get("id") or f"cat:{p.parent.name.lower().replace(' ', '_')}:{p.stem.lower().replace(' ', '_')}"
            tags = sorted(set(re.findall(r"[a-z]{3,}", p.stem.lower().replace("_", " "))) |
                          set((old or {}).get("tags", [])))
            entry = {**(old or {}), "id": aid, "kind": kind, "role": role, "path": relp, "hash": file_hash(p),
                     **t, **{k: v for k, v in lic.items() if v is not None or k == "commercial"},
                     "tags": tags, "tier": tier_of(p.resolve()), "embedding": None,
                     "embedding_note": "CLAP unavailable (needs torch); search uses tags and features",
                     "tagged_on": str(_dt.date.today())}
            by_path[relp] = entry
            n_new += 1
    cat["assets"] = list(by_path.values())
    write_json(out, cat)
    log(f"catalog: {len(cat['assets'])} assets ({n_new} tagged now) -> {out}")
    return cat


FEATURE_WORDS = {"short": ("duration_s", "<", 0.6), "long": ("duration_s", ">", 1.0), "bright": ("brightness_hz", ">", 3000),
                 "dark": ("brightness_hz", "<", 1500), "soft": ("lufs", "<", -22), "loud": ("lufs", ">", -16),
                 "punchy": ("attack_s", "<", 0.02), "slow": ("bpm", "<", 95), "fast": ("bpm", ">", 120)}


def find(query: str, kind: str | None, limit: int) -> list[dict]:
    cat_path = SKILL / "assets" / "catalog.json"
    if not cat_path.exists():
        fail("assets/catalog.json missing; run tag_assets.py first")
    words = query.lower().split()
    res = []
    for e in read_json(cat_path)["assets"]:
        if kind and e.get("kind") != kind:
            continue
        sc = 0.0
        hay = " ".join([*(e.get("tags") or []), e.get("role") or "", str(e.get("title") or "")]).lower()
        for w in words:
            if w in hay:
                sc += 2
            if w in FEATURE_WORDS:
                f, op, v = FEATURE_WORDS[w]
                x = e.get(f)
                if x is not None and ((op == "<" and x < v) or (op == ">" and x > v)):
                    sc += 1
            if w in ROLE_WORDS and e.get("role") == ROLE_WORDS[w]:
                sc += 3
        if sc:
            res.append({"score": sc, "id": e["id"], "role": e.get("role"), "path": e["path"],
                        "license": e.get("license"), "commercial": e.get("commercial"), "tier": e.get("tier")})
    return sorted(res, key=lambda r: (-r["score"], r.get("tier") or 9))[:limit]


PREFER = {"bright": lambda e: (e.get("brightness_hz") or 0), "dark": lambda e: -(e.get("brightness_hz") or 0),
          "soft": lambda e: -(e.get("lufs") or -30), "smooth": lambda e: (e.get("attack_s") or 0)}


def build_kit(catalog: Path, manifest: Path) -> dict:
    """Fill the kit manifest's role slots from tagged pack files (library/ and local/ only).
    Synthesized fallbacks stay at the end of the list; kit_path() takes the first entry on disk."""
    import json
    man = json.loads(manifest.read_text(encoding="utf-8"))
    cat = json.loads(catalog.read_text(encoding="utf-8")).get("assets", [])
    packs = [e for e in cat if e.get("kind") == "sfx" and e.get("commercial") is not False
             and ("/library/" in "/" + e["path"] or "/local/" in "/" + e["path"])]
    sounds, report = [], {}
    for role, spec in man["roles"].items():
        cands = [e for e in packs if e.get("role") == spec["catalog_role"]
                 and spec["min_s"] <= (e.get("duration_s") or 0) <= spec["max_s"]]
        cands.sort(key=PREFER.get(spec.get("prefer"), lambda e: 0), reverse=True)
        picked = cands[: spec["target"]]
        for e in picked:
            parts = Path(e["path"]).parts
            base = next(i for i, x in enumerate(parts) if x in ("library", "local"))
            sounds.append({"id": e["id"], "role": role, "pack": parts[base + 1] if len(parts) > base + 2 else "",
                           "file": "/".join(parts[base + 2:]) if len(parts) > base + 2 else parts[-1],
                           "source": e.get("source"), "license": e.get("license"), "attribution": e.get("attribution"),
                           "duration_s": e.get("duration_s"), "brightness_hz": e.get("brightness_hz")})
        report[role] = f"{len(picked)}/{spec['target']}"
    man["sounds"] = sounds + [s for s in man.get("sounds", []) if s.get("fallback")]
    manifest.write_text(json.dumps(man, indent=2), encoding="utf-8")
    return report


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", default="build",
                    help="build (default), find, or kit (fill assets/kit/manifest.json from tagged packs)")
    ap.add_argument("query", nargs="?")
    ap.add_argument("--roots", nargs="*", default=None)
    ap.add_argument("--vocals", action="store_true", help="check music for vocals with Whisper tiny")
    ap.add_argument("--only-new", action="store_true")
    ap.add_argument("--kind"); ap.add_argument("--limit", type=int, default=5)
    ap.add_argument("--out", default=str(SKILL / "assets" / "catalog.json"))
    a = ap.parse_args()
    if a.cmd == "find":
        if not a.query:
            fail("find needs a query, e.g. find \"short bright whoosh\"")
        res = find(a.query, a.kind, a.limit)
        print(__import__("json").dumps({"query": a.query, "method": "tags + measured features (no embeddings)",
                                         "results": res}, indent=2))
        return
    if a.cmd == "kit":
        man = SKILL / "assets" / "kit" / "manifest.json"
        if not Path(a.out).exists() or not man.exists():
            fail("kit needs assets/catalog.json (run build first) and assets/kit/manifest.json")
        rep = build_kit(Path(a.out), man)
        print(__import__("json").dumps({"filled": rep, "manifest": man.as_posix()}, indent=2))
        return
    roots = [Path(r) for r in a.roots] if a.roots else [SKILL / "assets" / d for d in ("local", "library", "kit", "cache")]
    build(roots, a.vocals, a.only_new, Path(a.out))


if __name__ == "__main__":
    main()
